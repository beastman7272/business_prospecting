from searcher_profiles.base import SearcherProfile, SegmentPlay

_RATIONALE = ("Executive, leadership-team, and full-org headshots plus an "
             "ongoing image-continuity program tied to onboarding; the buyer "
             "owns brand imagery and new-hire onboarding.")
_TACTICS = [
    'site:{domain} team OR leadership OR staff OR "our people"',
    '"{company}" "{city}" "marketing" OR "communications" OR "human resources" OR "office manager"',
    '"{company}" linkedin "{city}"',
]


def _p(seg_id, ranked, probe=None):
    return SegmentPlay(
        segment_id=seg_id, ranked_roles=ranked, probe_roles=probe or [],
        sales_rationale=_RATIONALE, search_tactics=_TACTICS,
    )


